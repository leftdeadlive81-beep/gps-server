-- ============================================================
-- 犯罪発生情報の地名→座標キャッシュ
-- ============================================================
-- 熊本県警オープンデータ（data.bodik.jp）のCSVには町丁目レベルの
-- 地名しか無く、緯度経度が含まれていない。Nominatimでジオコーディング
-- した結果をここに永続化し、サーバー再起動のたびに同じ地名を
-- 何度もジオコーディングしにいかないようにする。
-- lat/lonがNULLなのは「ジオコーディングを試みたが失敗した」地名
-- （再度リトライしない）
-- ============================================================

CREATE TABLE IF NOT EXISTS crime_geocode_cache (
    location_key TEXT PRIMARY KEY,
    lat DOUBLE PRECISION,
    lon DOUBLE PRECISION,
    geocoded_at BIGINT NOT NULL
);
